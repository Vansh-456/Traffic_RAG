log = get_logger(__name__)

SOURCE_LABELS = {
    "official": "Delhi Traffic Police (official)",
    "news": "News report",
    "sensor": "TomTom live traffic sensor",
}
EVENT_TYPES_FOR_CALENDAR = {"festival", "sports_event", "procession", "vip_movement", "protest"}


@dataclass
class DocumentDraft:
    """Everything a source connector knows about one item."""

    source_id: str
    url: str
    title: str
    trust_level: str
    content_type: str  # pdf | html | text
    raw: bytes | None = None
    body_text: str | None = None
    published_at: datetime | None = None
    authority: str | None = None
    publisher: str | None = None
    language: str | None = None
    valid_from_hint: datetime | None = None
    valid_to_hint: datetime | None = None
    http_status: int | None = 200
    metadata: dict[str, Any] = field(default_factory=dict)

    def content_hash(self) -> str:
        payload = self.raw if self.raw is not None else (self.body_text or "").encode()
        return hashlib.sha256(payload + self.title.encode()).hexdigest()


@dataclass
class ProcessResult:
    document_id: int | None
    status: str  # new | updated | unchanged | failed | empty
    chunk_ids: list[int] = field(default_factory=list)
    stages: dict[str, Any] = field(default_factory=dict)


def _cache_raw(draft: DocumentDraft, digest: str) -> str | None:
    if draft.raw is None:
        return None
    ext = {"pdf": "pdf", "html": "html"}.get(draft.content_type, "txt")
    path = Path(get_settings().raw_dir) / draft.source_id / f"{digest}.{ext}"
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists():
            path.write_bytes(draft.raw)
        return str(path)
    except OSError as exc:
        log.warning("raw cache write failed", extra={"err": str(exc)})
        return None


async def _parse(draft: DocumentDraft) -> tuple[str, str]:
    if draft.content_type == "pdf" and draft.raw:
        parsed = await parse_pdf(draft.raw)
        return clean_text(parsed.text), parsed.method
    if draft.content_type == "html" and draft.raw and not draft.body_text:
        return extract_main_text(draft.raw.decode("utf-8", errors="ignore"), draft.url), "html"
    return clean_text(draft.body_text or ""), "feed" if draft.trust_level == "news" else "text"


def _chunk_geometry(matches: list[GeoMatch]) -> BaseGeometry | None:
    geoms = []
    for m in matches:
        g = m.geometry
        geoms.append(buffer_m(g, 150) if g.geom_type != "Point" else g)
    if not geoms:
        return None
    return unary_union(geoms)


async def process(
    session: AsyncSession, draft: DocumentDraft, *, force: bool = False
) -> ProcessResult:
    """Run the full pipeline for one document draft inside `session`."""
    digest = draft.content_hash()
    stages: dict[str, Any] = {}
    existing = (
        await session.execute(select(Document).where(Document.url == draft.url))
    ).scalar_one_or_none()
    if existing and existing.content_hash == digest and existing.status == "ready" and not force:
        INGEST_ITEMS.labels(draft.source_id, "unchanged").inc()
        return ProcessResult(existing.id, "unchanged")

    # 1. raw cache
    raw_path = _cache_raw(draft, digest)
    raw_stmt = (
        insert(RawDocument)
        .values(
            source_id=draft.source_id,
            url=draft.url,
            fetched_at=utcnow(),
            content_hash=digest,
            content_type=draft.content_type,
            raw_path=raw_path,
            http_status=draft.http_status,
        )
        .on_conflict_do_nothing(constraint="uq_raw_documents_url_hash")
        .returning(RawDocument.id)
    )
    raw_id = (await session.execute(raw_stmt)).scalar_one_or_none()

    # 2. parse
    body, method = await _parse(draft)
    language = draft.language or detect_document_language(f"{draft.title}\n{body}")
    stages["parse"] = {"method": method, "chars": len(body), "language": language}
    if not body.strip():
        body = draft.title

    # upsert document
    if existing is None:
        doc = Document(
            source_id=draft.source_id,
            url=draft.url,
            title=draft.title[:1000],
            trust_level=draft.trust_level,
            content_hash=digest,
        )
        session.add(doc)
        status = "new"
    else:
        doc = existing
        await session.execute(delete(Chunk).where(Chunk.document_id == doc.id))
        status = "updated"
    doc.raw_document_id = raw_id or doc.raw_document_id
    doc.title = draft.title[:1000]
    doc.authority = draft.authority
    doc.publisher = draft.publisher
    doc.language = language
    doc.published_at = draft.published_at
    doc.content_hash = digest
    doc.text = body
    doc.parse_method = method
    doc.status = "processing"
    doc.metadata_ = {**draft.metadata}
    await session.flush()

    # 3. chunk
    drafts = chunking.chunk_text(body)
    stages["chunk"] = {"chunks": len(drafts), "tokens": [d.token_count for d in drafts]}
    source_label = SOURCE_LABELS.get(draft.trust_level, draft.trust_level)

    # 4. enrich (bounded concurrency; the LLM limiter enforces RPM)
    sem = asyncio.Semaphore(3)

    async def _enrich(d: chunking.ChunkDraft) -> tuple[Enrichment, str]:
        async with sem:
            return await enrich_chunk(
                d.text,
                title=draft.title,
                published_at=draft.published_at,
                source_label=source_label,
            )

    enrichments = await asyncio.gather(*(_enrich(d) for d in drafts))
    stages["enrich"] = {"methods": sorted({m for _, m in enrichments})}

    geocoder = await get_db_geocoder(session)
    chunk_rows: list[tuple[Chunk, Enrichment, list[GeoMatch]]] = []
    for d, (enr, enr_method) in zip(drafts, enrichments, strict=True):
        vf, vt = enr.parsed_window()
        vf = vf or draft.valid_from_hint
        vt = vt or draft.valid_to_hint
        header = chunking.build_context_header(
            title=draft.title,
            authority=draft.authority or draft.publisher,
            published_at=draft.published_at,
            valid_from=vf,
            valid_to=vt,
            section=d.section,
            source_label=source_label,
        )
        # 5. geocode
        mentions = list(dict.fromkeys([*enr.locations, *enr.roads]))
        matches = await geocoder.geocode_many(mentions, session)
        geom = _chunk_geometry(matches)
        chunk = Chunk(
            document_id=doc.id,
            ordinal=d.ordinal,
            section=d.section,
            text=d.text,
            text_with_context=chunking.with_context(header, d.text),
            token_count=d.token_count,
            language=language,
            event_type=enr.event_type,
            severity=enr.severity,
            valid_from=vf,
            valid_to=vt,
            published_at=draft.published_at,
            trust_level=draft.trust_level,
            is_active=vt is None or vt >= utcnow(),
            status="pending",
            simhash=simhash64(d.text),
            metadata_={
                "enrichment": enr_method,
                "locations": enr.locations,
                "roads": enr.roads,
                "diversion_points": enr.diversion_points,
                "restricted_roads": enr.restricted_roads,
                "alternate_routes": enr.alternate_routes,
                "summary_en": enr.summary_en,
                "summary_hi": enr.summary_hi,
                "questions": enr.hypothetical_questions,
                "geocoded": [m.to_dict() for m in matches],
                **{k: v for k, v in draft.metadata.items() if k in ("category", "link")},
            },
        )
        if geom is not None:
            chunk.geom = f"SRID=4326;{geom.wkt}"
        session.add(chunk)
        chunk_rows.append((chunk, enr, matches))
    await session.flush()

    for chunk, _, matches in chunk_rows:
        for m in matches:
            session.add(
                ChunkLocation(
                    chunk_id=chunk.id,
                    place_id=m.place_id,
                    mention=m.mention[:500],
                    method=m.method,
                    confidence=m.confidence,
                    geom=f"SRID=4326;{m.geometry.wkt}",
                )
            )
    stages["geocode"] = {"resolved": sum(len(m) for _, _, m in chunk_rows)}

    # 6. embed
    vectors = await embed_chunk_texts(
        session, [(c.id, c.text_with_context) for c, _, _ in chunk_rows]
    )
    n_questions = 0
    for chunk, enr, _ in chunk_rows:
        n_questions += await embed_questions(session, chunk.id, enr.hypothetical_questions)
    stages["embed"] = {"chunks": len(vectors), "questions": n_questions}
    await session.flush()

    # 7. dedup
    dedup_reports = []
    for chunk, _, _ in chunk_rows:
        dedup_reports.append(
            await assign_cluster(
                session,
                chunk_id=chunk.id,
                document_id=doc.id,
                simhash=chunk.simhash or 0,
                embedding=vectors[chunk.id],
                published_at=draft.published_at,
            )
        )
    stages["dedup"] = {"clustered": sum(1 for r in dedup_reports if r.get("clustered"))}

    # events calendar
    for chunk, enr, matches in chunk_rows:
        if enr.event_type in EVENT_TYPES_FOR_CALENDAR and chunk.valid_from:
            session.add(
                Event(
                    name=draft.title[:300],
                    venue=matches[0].name if matches else None,
                    place_id=matches[0].place_id if matches else None,
                    start_at=chunk.valid_from,
                    end_at=chunk.valid_to,
                    source="extracted",
                    chunk_id=chunk.id,
                )
            )

    # 9. mark ready
    for chunk, _, _ in chunk_rows:
        chunk.status = "ready"
    doc.status = "ready"
    await session.flush()
    await link_translations(session, doc)

    chunk_ids = [c.id for c, _, _ in chunk_rows]
    try:
        if not get_settings().publish_events:
            raise RuntimeError("publishing disabled")
        await get_redis().publish(
            CHANNEL_NEW_CHUNK,
            json.dumps({"document_id": doc.id, "chunk_ids": chunk_ids, "source": draft.source_id}),
        )
    except Exception as exc:
        log.debug("new_chunk not published", extra={"err": str(exc)})
    INGEST_ITEMS.labels(draft.source_id, status).inc()
    log.info(
        "document processed",
        extra={"doc_id": doc.id, "url": draft.url, "status": status, "stages": stages},
    )
    return ProcessResult(doc.id, status, chunk_ids, stages)


async def link_translations(session: AsyncSession, doc: Document) -> int | None:
    """Link Hindi/English versions of the same advisory.

    Heuristic: same source, other language, published within 36 h, and the
    chunks overlap in validity window (same start date) or in ≥ 2 geocoded
    places. Linking is symmetric.
    """
    if doc.language not in ("hi", "en") or doc.published_at is None:
        return None
    row = (
        await session.execute(
            text(
                """
                WITH me AS (
                  SELECT min(valid_from)::date AS vf,
                         array_agg(DISTINCT cl.place_id) FILTER (WHERE cl.place_id IS NOT NULL) AS places
                  FROM chunks c LEFT JOIN chunk_locations cl ON cl.chunk_id = c.id
                  WHERE c.document_id = :doc
                )
                SELECT d.id
                FROM documents d
                JOIN chunks c ON c.document_id = d.id
                LEFT JOIN chunk_locations cl ON cl.chunk_id = c.id, me
                WHERE d.source_id = :src AND d.id <> :doc AND d.language IN ('hi','en')
                  AND d.language <> :lang
                  AND abs(extract(epoch FROM d.published_at - :pub)) < 129600
                GROUP BY d.id, me.vf, me.places
                HAVING min(c.valid_from)::date = me.vf
                    OR count(DISTINCT cl.place_id) FILTER (WHERE cl.place_id = ANY(me.places)) >= 2
                ORDER BY abs(extract(epoch FROM max(d.published_at) - :pub))
                LIMIT 1
                """
            ),
            {"doc": doc.id, "src": doc.source_id, "lang": doc.language, "pub": doc.published_at},
        )
    ).first()
    if row is None:
        return None
    other_id = int(row.id)
    doc.linked_document_id = other_id
    await session.execute(
        text("UPDATE documents SET linked_document_id = :me WHERE id = :other"),
        {"me": doc.id, "other": other_id},
    )
    return other_id
