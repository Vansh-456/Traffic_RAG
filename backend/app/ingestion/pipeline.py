"""End-to-end processing of one document (Section 5 of the spec).

Stages (each idempotent and logged):
 1. fetch & cache raw     → raw_documents + file under DATA_DIR/raw
 2. parse & clean         → text, language, parse method
 3. structure-aware chunk → ChunkDraft list
 4. LLM enrichment        → event type, locations, validity, summary, questions
 5. geocoding             → chunk_locations + chunk geometry
 6. embed                 → chunk_embeddings + question_embeddings
 7. dedup                 → dedup_cluster_id / is_canonical
 8. sparse index          → tsvector columns are generated by Postgres
 9. mark ready + publish  → Redis `events:new_chunk`
"""

